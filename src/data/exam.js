// 依簡章：總分 = 科一 × 40% + 科二 × 60%，總分 ≥ 70 且任一科 ≥ 60
export function judge(s1, s2) {
	const r = v => Math.round(v * 100) / 100
	const total = r(s1 * 0.4 + s2 * 0.6)
	const pass = total >= 70 && s1 >= 60 && s2 >= 60
	let reason = ''
	if (!pass) {
		if (s1 < 60 && s2 < 60) reason = '兩科皆低於 60 分'
		else if (s1 < 60) reason = '科目一低於 60 分'
		else if (s2 < 60) reason = '科目二低於 60 分'
		else reason = '總成績未達 70 分'
	}
	return { total, pass, reason }
}
